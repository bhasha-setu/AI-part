"""Scripted demo that produces a human-readable sample session transcript.

Running ``python -m guided_practice.demo`` writes:
    samples/sample_session.md    -- what a learner would see
    samples/sample_session.jsonl -- the raw turn log

A fixed clock and session id make the output deterministic, so a golden test
can regenerate it and compare.

The scripted learner needs hints on items 1 and 3, solves item 2 at level 0,
and makes one surface error and one meaning error along the way.
"""

from __future__ import annotations

from datetime import datetime, timedelta, timezone
from pathlib import Path

from .config import DEFAULT_COURSE
from .course import load_course
from .evaluator import RuleEvaluator, StubLLMJudge
from .session import Session
from .summary import summarise
from .turn_log import JsonlLogger

SAMPLES_DIR = Path(__file__).resolve().parent.parent / "samples"

# Course-specific script for the English-for-Hindi introducing_yourself scenario.
# Another course needs its own script; the core does not change.
# Transcript strings the scripted learner submits, in order.
SCRIPT = [
    "Hello there",            # item1 L0: off-target -> meaning_error -> L1
    "my name Ravi",           # item1 L1: missing copula -> surface_error (retry)
    "my name is Ravi",        # item1 L1: correct (produced, independent)
    "I'm fine, thank you",    # item1 follow-up answer (unscored)
    "I'm from Dehradun",      # item2 L0: correct (produced, independent)
    "I work",                 # item3 L0: meaning_error -> L1
    "hmm",                    # item3 L1: meaning_error -> L2
    "I am student",           # item3 L2: dropped article -> surface_error (retry)
    "I am a student",         # item3 L2: correct (produced, NOT independent)
    "I like cricket",         # item4 L0: correct (produced, independent)
]


def _fixed_clock(step_seconds: int = 30):
    base = datetime(2025, 1, 6, 9, 0, 0, tzinfo=timezone.utc)
    n = {"i": 0}

    def clock():
        n["i"] += 1
        return base + timedelta(seconds=step_seconds * n["i"])

    return clock


def run_demo(log_path: Path | str, course_id: str = DEFAULT_COURSE):
    """Run the scripted session, returning (transcript_lines, summary, judge)."""
    course = load_course(course_id)
    scenario = course.load_scenario("introducing_yourself")
    judge = StubLLMJudge()
    evaluator = RuleEvaluator(llm=judge)
    logger = JsonlLogger(log_path)

    session = Session(
        scenario=scenario,
        learner_id="demo-learner",
        evaluator=evaluator,
        logger=logger,
        clock=_fixed_clock(),
        session_id="demo-session",
        course=course,
    )

    lines: list[str] = []
    prompt = session.start()
    lines.append(f"APP:     {prompt}")

    for transcript in SCRIPT:
        if session.done:
            break
        result = session.submit(transcript, why=False)
        lines.append(f"LEARNER: {transcript}")
        lines.append(f"   -> verdict: {result.verdict}")
        if result.feedback:
            lines.append(f"APP:     {result.feedback}")
        if result.prompt:
            lines.append(f"APP:     {result.prompt}")
        lines.append("")

    records = JsonlLogger.read(log_path)
    summary = summarise(records, session_id="demo-session")
    return lines, summary, judge


def render_markdown(lines, summary) -> str:
    out = ["# Sample guided-practice session", ""]
    out.append("_Generated by `python -m guided_practice.demo` (deterministic)._")
    out.append("")
    out.append("Scenario: **Introducing yourself** · Learner: demo-learner (A1)")
    out.append("")
    out.append("## Transcript")
    out.append("")
    out.append("```")
    out.extend(lines)
    out.append("```")
    out.append("")
    out.append("## Session summary")
    out.append("")
    out.append(f"- Items attempted: {len(summary.items_attempted)}")
    out.append("- Hint level reached per item (level of first acceptable answer):")
    for item_id, lvl in summary.hint_level_per_item.items():
        shown = "not achieved" if lvl is None else f"level {lvl}"
        outcome = summary.outcome_per_item.get(item_id, "")
        out.append(f"    - {item_id}: {shown} ({outcome})")
    out.append(
        f"- Independence score (solved at level 0 or 1): "
        f"{summary.independence_score:.2f}"
    )
    out.append(f"- Items to schedule for review: {summary.review_items or 'none'}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    import shutil
    import tempfile

    SAMPLES_DIR.mkdir(parents=True, exist_ok=True)
    jsonl_path = SAMPLES_DIR / "sample_session.jsonl"
    if jsonl_path.exists():
        jsonl_path.unlink()  # fresh run each time (deterministic)
    lines, summary, _ = run_demo(jsonl_path)
    md = render_markdown(lines, summary)
    (SAMPLES_DIR / "sample_session.md").write_text(md, encoding="utf-8")

    workdir = Path(tempfile.mkdtemp())
    try:
        lesson_lines, lesson = run_lesson_demo(workdir)
        lesson_md = render_lesson_markdown(lesson_lines, lesson)
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    (SAMPLES_DIR / "sample_lesson.md").write_text(lesson_md, encoding="utf-8")
    print(md)
    print(lesson_md)




# --- whole-lesson sample ------------------------------------------------------

# Transcripts for the guided-practice stage, in order. The follow-up answer is
# included where the scenario asks a follow-up question.
LESSON_SCRIPT = [
    "Hello there",            # intro_name L0: meaning -> L1
    "my name Ravi",           # intro_name L1: surface (retry)
    "my name is Ravi",        # intro_name L1: correct
    "I'm fine, thank you",    # follow-up (unscored)
    "I'm from Dehradun",      # intro_origin L0: correct
    "I work",                 # intro_work L0: meaning -> L1
    "hmm",                    # intro_work L1: off_topic -> L2
    "I am student",           # intro_work L2: surface (retry)
    "I am a student",         # intro_work L2: correct (heavy help)
    "I like cricket",         # intro_interest L0: correct
]


def run_lesson_demo(workdir: Path | str, course_id: str = DEFAULT_COURSE):
    """Run a whole scripted lesson. Returns (transcript_lines, lesson)."""
    from .lesson import Lesson

    course = load_course(course_id)
    workdir = Path(workdir)
    lesson = Lesson(
        course, "introducing_yourself", "demo-learner",
        workdir / "learners.json", workdir / "lesson_log.jsonl",
        # Scripted time: 5 s per clock read. Elapsed figures are not real timings.
        clock=_fixed_clock(step_seconds=5), lesson_id="demo-lesson",
    )
    lines: list[str] = []
    script = iter(LESSON_SCRIPT)

    view = lesson.start()
    _show_presentation(view, lines)
    while view.expects not in ("done", "held"):
        if view.expects == "continue":
            view = lesson.continue_()
            _show_presentation(view, lines)
            continue
        text = next(script)
        view = lesson.submit(text, why=False)
        lines.append(f"LEARNER: {text}")
        if view.feedback:
            lines.append(f"APP:     {view.feedback}")
        if view.prompt and view.expects == "answer":
            lines.append(f"APP:     {view.prompt}")
        lines.append("")
    if lesson.status == "held":
        lines.append(f"LESSON:  held ({view.reason})")
    else:
        lines.append(f"LESSON:  {lesson.status}")
    return lines, lesson


def _show_presentation(view, lines: list[str]) -> None:
    if view.stage == "guided_practice" or view.expects == "answer":
        lines.append(f"-- {view.lines[0] if view.lines else view.stage} --")
        if view.prompt:
            lines.append(f"APP:     {view.prompt}")
        lines.append("")
        return
    if view.expects == "continue":
        lines.append(f"-- {view.lines[0]} --")
        lines.extend(f"         {line}" for line in view.lines[1:-1])
        lines.append(f"         {view.lines[-1]}")
        lines.append("")


def render_lesson_markdown(lines, lesson) -> str:
    out = ["# Sample lesson", ""]
    out.append("_Generated by `python -m guided_practice.demo` (deterministic)._")
    out.append("")
    out.append("Scenario: **Introducing yourself** · Course: English for Hindi-speaking A1 (DRAFT)")
    out.append("")
    out.append("## Transcript")
    out.append("")
    out.append("```")
    out.extend(lines)
    out.append("```")
    out.append("")
    out.append("## Stages")
    out.append("")
    out.append("_Elapsed times come from a scripted clock (5 s per read), not real timing._")
    out.append("")
    out.append("| Stage | Status | Budget (s) | Elapsed (s) | Over budget |")
    out.append("|---|---|---|---|---|")
    for r in lesson.records:
        out.append(f"| {r.stage} | {r.status} | {r.budget_seconds} | "
                   f"{r.elapsed_seconds:.0f} | {'yes' if r.over_budget else 'no'} |")
    out.append("")
    if lesson.assessment is not None:
        s = lesson.assessment
        out.append("## Assessment (stubs marked)")
        out.append("")
        for name in ("task_completion", "independence", "clarity", "grammar",
                     "vocabulary", "comprehension", "improvement_goal"):
            v = getattr(s, name)
            shown = "stub (not computed)" if v.value is None else v.value
            out.append(f"- {name}: {shown} _(basis: {v.basis})_")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    main()
